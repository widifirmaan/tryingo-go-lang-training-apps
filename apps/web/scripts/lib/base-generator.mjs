import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
// __dirname = scripts/lib/, so ../.. = apps/web/
const APP_ROOT = path.resolve(__dirname, '../..');
const BASE_COURSE = path.join(APP_ROOT, 'public/data/course');
const BASE_CURRICULA = path.join(APP_ROOT, 'src/data/curricula');

// ─────────────────────────────────────────────────────────────────────────────
// BASE GENERATOR UTILITY
// Usage: import { BaseGenerator } from '../lib/base-generator.mjs'
// ─────────────────────────────────────────────────────────────────────────────
export class BaseGenerator {
  constructor(slug, trackName) {
    this.slug = slug;
    this.trackName = trackName;
    this.courseDir = path.join(BASE_COURSE, slug);
    this.curriculaDir = BASE_CURRICULA;
  }

  // Generate markdown content for a module
  generateMarkdown(module, isId) {
    const lang = isId ? 'id' : 'en';
    const title = isId ? module.titleId : module.titleEn;
    const programTitle = isId ? module.programId : module.programEn;
    const objectives = isId ? module.objectivesId : module.objectivesEn;
    const explanation = isId ? module.explanationId : module.explanationEn;
    const experiments = isId ? module.experimentsId : module.experimentsEn;
    const challenge = isId ? module.challengeId : module.challengeEn;
    const summary = isId ? module.summaryId : module.summaryEn;

    const objectivesList = objectives.map(o => '- ' + o).join('\n');
    const experimentsList = experiments.map(e => '- ' + e).join('\n');

    const levelName = isId ? module.levelNameId : module.levelNameEn;

    return `# ${title}

> **Kategori:** ${this.trackName} | **Level:** ${levelName} | **Minggu ${module.week}:** ${title}

## ${isId ? 'Tujuan Pembelajaran' : 'Learning Objectives'}

${objectivesList}

---

## ${isId ? 'Program' : 'Program'}: ${programTitle}

\`\`\`${module.language || this.slug}
${module.code}
\`\`\`

---

## ${isId ? 'Konsep Kunci' : 'Key Concepts'}

${explanation}

---

## ${isId ? 'Eksperimen' : 'Experiments'}

${experimentsList}

---

## ${isId ? 'Tantangan' : 'Challenge'}

${challenge}

---

## ${isId ? 'Ringkasan' : 'Summary'}

${summary}
`;
  }

  // Write all files for a track
  writeFiles(modules, levels) {
    // Write markdown files
    for (const mod of modules) {
      for (const lang of ['id', 'en']) {
        const dir = path.join(this.courseDir, mod.level, lang);
        fs.mkdirSync(dir, { recursive: true });
        const content = this.generateMarkdown(mod, lang === 'id');
        const fileName = `week${mod.week}-${mod.topicId}.md`;
        fs.writeFileSync(path.join(dir, fileName), content, 'utf8');
      }
    }

    // Generate curriculum.ts file
    this.generateCurriculumFile(levels);

    console.log(`\n✓ Generated ${modules.length * 2} ${this.trackName} curriculum files (${modules.length} modules × 2 languages)`);
    console.log(`  Structure: ${levels.length} levels × ${modules.length} weeks (research-backed)`);
    console.log(`  Output: ${this.courseDir}`);
  }

  // Generate the curriculum.ts file for src/data/curricula/{slug}.ts
  generateCurriculumFile(levels) {
    fs.mkdirSync(this.curriculaDir, { recursive: true });

    const levelsTs = levels.map(level => {
      const weeksTs = level.weeks.map(w => 
        `      { week: ${w.week}, topicId: '${w.topicId}', titleId: '${w.titleId}', titleEn: '${w.titleEn}' }`
      ).join(',\n');

      return `  {
    levelId: '${level.levelId}',
    nameId: '${level.nameId}',
    nameEn: '${level.nameEn}',
    descId: '${level.descId}',
    descEn: '${level.descEn}',
    weeks: [
${weeksTs}
    ],
  }`;
    }).join(',\n');

    const tsContent = `import type { LevelInfo } from '../curriculum';

// ${this.trackName} curriculum — research-backed structure
// Generated by generate-${this.slug}-materials.mjs
export const ${this.slug}Curriculum: LevelInfo[] = [
${levelsTs}
];
`;

    fs.writeFileSync(path.join(this.curriculaDir, `${this.slug}.ts`), tsContent, 'utf8');
  }
}
